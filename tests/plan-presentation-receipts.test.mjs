import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {readBundleWorkspace} from '../lib/home-bundle-records.ts';
import {bundleInputKey} from '../lib/home-bundle-reconciliation.ts';
import {actionPlanQuickSummary} from '../lib/action-plan-quick-summary.ts';
import {planBudgetText} from '../lib/home-plan-revisions.ts';
const frozen=JSON.parse(readFileSync(new URL('./fixtures/pre-layout-known-receipt.json',import.meta.url)));
const legacy=JSON.parse(readFileSync(new URL('./fixtures/home-plan-legacy-costs.json',import.meta.url)));
test('receipt generated by pre-layout source retains accepted visible-summary values',()=>{
 const before=JSON.stringify(frozen.raw),read=readBundleWorkspace(frozen.raw,frozen.raw.goalId);
 assert.ok(read);assert.equal(JSON.stringify(read),before);
 const {draft,result}=read.attachments[0];
 assert.equal(result.inputKey,bundleInputKey(draft));
 const summary=actionPlanQuickSummary(draft,result);
 assert.equal(summary.current,true);assert.equal(summary.cash,3000);
 assert.equal(summary.people,10);assert.equal(summary.deliveryHours,36);
 assert.equal(summary.finish,'2026-11-28');assert.equal(summary.coverage,'reviewed');
 assert.equal(JSON.stringify(frozen.raw),before);
});
test('mismatched historical input keys are already rejected at the storage boundary',()=>{
 const raw=structuredClone(frozen.raw);raw.attachments[0].result.inputKey='different-inputs';
 const before=JSON.stringify(raw);assert.equal(readBundleWorkspace(raw,raw.goalId),null);
 assert.equal(actionPlanQuickSummary(raw.attachments[0].draft,raw.attachments[0].result).cash,null);
 assert.equal(JSON.stringify(raw),before);
});
test('genuine legacy budget receipt retains original cash wording without pricing staff time',()=>{
 const before=JSON.stringify(legacy.workspace),read=readBundleWorkspace(legacy.workspace,legacy.workspace.goalId);
 assert.ok(read);const {draft,result}=read.attachments[0];
 assert.equal(result.budget.headroom,-200); // Original all-in receipt is not rewritten.
 assert.match(planBudgetText(result),/\$2,500 USD headroom under the listed assumptions/);
 assert.match(planBudgetText(result),/actual costs and funding remain unverified/);
 assert.doesNotMatch(planBudgetText(result),/\$2,700|\$6,200/);
 assert.equal(actionPlanQuickSummary(draft,result).deliveryHours,36);
 assert.equal(JSON.stringify(read),before);assert.equal(JSON.stringify(legacy.workspace),before);
});
